	private final String[] rows;

	Icon(String... rows) {
		for (String r : rows) {
			if (r.length() != rows[0].length() || !r.matches("[#.]+")) {
				throw new IllegalArgumentException(Tr.f("ドット絵の行の長さか字が違う: {0} {1}", name(), r));
			}
		}

		this.rows = rows;
	}

	public int width() {
		return rows[0].length();
	}

	public int height() {
		return rows.length;
	}

	/** (col, row) を塗るか (テスト用)。 */
	public boolean dot(int col, int row) {
		return rows[row].charAt(col) == '#';
	}

	/** 左上を (x, y) にして描く。横に続く点はまとめて塗る。 */
	public void draw(GuiGraphicsExtractor g, int x, int y, int color) {
		for (int r = 0; r < rows.length; r++) {
			String row = rows[r];
			int start = -1;

			for (int c = 0; c <= row.length(); c++) {
				boolean on = c < row.length() && row.charAt(c) == '#';

				if (on && start < 0) {
					start = c;
				} else if (!on && start >= 0) {
					g.fill(x + start, y + r, x + c, y + r + 1, color);
					start = -1;
				}
			}
		}
	}
